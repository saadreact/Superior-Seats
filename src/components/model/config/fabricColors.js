/**
 * Get all colors for a specific fabric type
 * @param {string} fabricType - The fabric type identifier
 * @returns {Array} Array of color objects with name and hex
 */
export const getColorsForFabric = (fabricType) => {
  const fabric = fabricColors[fabricType];
  if (!fabric) return [];
  
  // Flatten all collections into a single array
  const allColors = [];
  Object.values(fabric.collections).forEach(collection => {
    allColors.push(...collection);
  });
  
  return allColors;
};

/**
 * Get fabric type display name
 * @param {string} fabricType - The fabric type identifier
 * @returns {string} Display name with icon
 */
export const getFabricDisplayName = (fabricType) => {
  const fabric = fabricColors[fabricType];
  return fabric ? `${fabric.icon} ${fabric.name}` : fabricType;
};

/**
 * Get collections for a specific fabric type
 * @param {string} fabricType - The fabric type identifier
 * @returns {Object} Collections object
 */
export const getCollectionsForFabric = (fabricType) => {
  const fabric = fabricColors[fabricType];
  return fabric ? fabric.collections : {};
};

/**
 * Find color by name across all fabric types
 * @param {string} colorName - The color name to search for
 * @returns {Object|null} Color object with hex value or null if not found
 */
export const findColorByName = (colorName) => {
  for (const fabric of Object.values(fabricColors)) {
    for (const collection of Object.values(fabric.collections)) {
      const color = collection.find(c => c.name === colorName);
      if (color) return color;
    }
  }
  return null;
};
